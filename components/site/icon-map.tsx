export type IconName = keyof typeof icons;

/**
 * Nama ikon yang tersedia, diturunkan dari peta di atas.
 *
 * Dipakai CMS sebagai pilihan tertutup. Sengaja TIDAK ditulis ulang sebagai
 * daftar terpisah: dua daftar yang harus diperbarui bersamaan pasti melenceng
 * suatu hari, dan ikon yang namanya tidak ada di peta tidak menampilkan apa
 * pun tanpa satu pun peringatan.
 */
export const namaIkon = Object.keys(icons).sort() as IconName[];

export function Icon({
  name,
  className,
  strokeWidth,
}: {
  name: string;
  className?: string;
  strokeWidth?: number;
}) {
  const Cmp = icons[name as IconName];
  if (!Cmp) return null;
  return (
    <Cmp className={className} strokeWidth={strokeWidth} aria-hidden="true" />
  );
}
